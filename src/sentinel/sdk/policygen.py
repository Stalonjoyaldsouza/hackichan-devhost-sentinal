"""Generate `.sentinel/policy.yaml` from the developer's selection and `config.yaml`.

The file is DERIVED — change `config.yaml` (default_action, point_actions, allowed domains) and
re-run `sentinel sdk policy`; selection changes regenerate it automatically. The deterministic
`PolicyEngine` from the core product evaluates it, so the SDK enforces with the same code path.
"""

from __future__ import annotations

import yaml

from sentinel.sdk.models import Category, tool_name_for
from sentinel.sdk.workspace import Config, Workspace

HEADER = ("# GENERATED by `sentinel sdk policy` — do not edit.\n"
          "# Edit .sentinel/config.yaml (default_action, point_actions, allowed_destination_domains)\n"
          "# and re-run `sentinel sdk policy`.\n")
SINK_CATEGORIES = {Category.EXTERNAL_API.value, Category.MESSAGING.value}
_SUFFIX = {"ALLOW": "A", "DENY": "D", "REQUIRE_APPROVAL": "R"}


def build_policy(cfg: Config, selected: list[str], categories: dict[str, str]) -> dict:
    tools = {tool_name_for(pid): {"protected": True, "safe_in_restricted": False,
                                  "description": f"SDK monitoring point {pid}"} for pid in selected}
    rules = []
    for pid in selected:
        action = cfg.point_actions.get(pid, cfg.default_action)
        match: dict = {"tools": [tool_name_for(pid)]}
        if action == "ALLOW":
            match["roles_any"] = ["app"]
        rules.append({"id": f"R-{pid[3:]}-{_SUFFIX[action]}", "effect": action, "match": match,
                      "reason": f"SDK_POINT_{action}",
                      "description": f"{action} for monitoring point {pid}"})
    sinks = [tool_name_for(pid) for pid in selected if categories.get(pid) in SINK_CATEGORIES]
    if sinks:
        flow_match: dict = {"tools": sinks, "data_labels_any": ["confidential", "pii"]}
        if cfg.allowed_destination_domains:
            flow_match["destination_domain_not_in"] = list(cfg.allowed_destination_domains)
        rules.insert(0, {"id": "R-DF-SENSITIVE-EXTERNAL", "effect": "DENY", "match": flow_match,
                         "reason": "SENSITIVE_DATA_TO_UNAPPROVED_DESTINATION",
                         "description": "Sensitive-labelled data may only reach allowed domains"})
    return {"version_label": "sdk-project", "approvers": list(cfg.approvers),
            "approval_ttl_seconds": 900, "tools": tools, "rules": rules}


def write_policy(ws: Workspace) -> tuple[int, int]:
    """(Re)write policy.yaml. Returns (selected points, rules)."""
    cfg = ws.load_config()
    selected = sorted(ws.load_selected())
    categories: dict[str, str] = {}
    if ws.analysis_path.exists():
        categories = {p.point_id: p.category.value for p in ws.load_analysis().points}
    policy = build_policy(cfg, selected, categories)
    ws.dir.mkdir(parents=True, exist_ok=True)
    tmp = ws.policy_path.with_suffix(".tmp")
    tmp.write_text(HEADER + yaml.safe_dump(policy, sort_keys=False))
    tmp.replace(ws.policy_path)  # atomic: a running app never sees a half-written policy
    return len(selected), len(policy["rules"])
